-- 알림함 (세션 진행·취소, 연락처 교환)
CREATE TABLE notification (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id         BIGINT       NOT NULL REFERENCES member (id),
    notification_type VARCHAR(50)  NOT NULL,
    title             VARCHAR(100) NOT NULL,
    body              VARCHAR(500) NOT NULL,
    session_id        BIGINT,
    link              VARCHAR(255),
    dedupe_key        VARCHAR(200) NOT NULL UNIQUE,
    created_at        TIMESTAMPTZ  NOT NULL,
    read_at           TIMESTAMPTZ
);

-- 내 알림 최신순 조회, 안 읽은 개수
CREATE INDEX idx_notification_member_created ON notification (member_id, created_at DESC);
CREATE INDEX idx_notification_member_unread ON notification (member_id) WHERE read_at IS NULL;

COMMENT ON TABLE notification IS '알림함. 앱을 닫고 있어도 나중에 확인해야 하는 세션·연락처 알림';
COMMENT ON COLUMN notification.dedupe_key IS '같은 일로 알림이 두 번 남지 않게 하는 키 (예: SESSION_CANCELLED:s12:m7)';
COMMENT ON COLUMN notification.link IS '알림을 눌렀을 때 이동할 프론트 경로';
