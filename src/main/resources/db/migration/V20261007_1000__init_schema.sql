-- =========================================================
-- 회원
-- =========================================================
CREATE TABLE member (
                        id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        public_id            UUID         NOT NULL UNIQUE,
                        email                VARCHAR(255) NOT NULL UNIQUE,
                        password_hash        VARCHAR(255) NOT NULL,
                        university           VARCHAR(255) NOT NULL,
                        gender               VARCHAR(10)  NOT NULL,
                        birth_date           DATE         NOT NULL,
                        phone_number         VARCHAR(255),
                        instagram_id         VARCHAR(255),
                        role                 VARCHAR(10)  NOT NULL,
                        member_status        VARCHAR(20)  NOT NULL,
                        email_verified_at    TIMESTAMPTZ  NOT NULL,
                        identity_verified_at TIMESTAMPTZ,
                        created_at           TIMESTAMPTZ  NOT NULL,
                        updated_at           TIMESTAMPTZ  NOT NULL,
    -- 탈퇴 회원을 빼고는 연락처 둘 중 하나는 필수
                        CONSTRAINT ck_member_contact
                            CHECK (member_status = 'WITHDRAWN' OR phone_number IS NOT NULL OR instagram_id IS NOT NULL)
);

CREATE TABLE email_verification (
                                    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    email         VARCHAR(255) NOT NULL,
                                    code_hash     VARCHAR(255) NOT NULL,
                                    attempt_count INT          NOT NULL DEFAULT 0,
                                    expires_at    TIMESTAMPTZ  NOT NULL,
                                    verified_at   TIMESTAMPTZ,
                                    created_at    TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_email_verification_email_created ON email_verification (email, created_at DESC);

CREATE TABLE profile (
                         id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         member_id     BIGINT       NOT NULL UNIQUE REFERENCES member (id),
                         university    VARCHAR(255) NOT NULL,
                         ideal_type    TEXT,
                         dating_style  TEXT,
                         contact_style TEXT,
                         love_style    TEXT,
                         created_at    TIMESTAMPTZ  NOT NULL,
                         updated_at    TIMESTAMPTZ  NOT NULL
);

CREATE TABLE profile_interest (
                                  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  profile_id BIGINT      NOT NULL REFERENCES profile (id) ON DELETE CASCADE,
                                  interest   VARCHAR(20) NOT NULL,
                                  created_at TIMESTAMPTZ NOT NULL,
                                  CONSTRAINT uk_profile_interest UNIQUE (profile_id, interest)
);

-- =========================================================
-- 세션·라이브
-- =========================================================
CREATE TABLE dating_session (
                                id                                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                start_time                        TIMESTAMPTZ NOT NULL,
                                capacity_per_gender               INT         NOT NULL CHECK (capacity_per_gender BETWEEN 3 AND 6),
                                round_duration_seconds            INT         NOT NULL CHECK (round_duration_seconds > 0),
                                voting_duration_seconds           INT         NOT NULL CHECK (voting_duration_seconds > 0),
                                result_and_share_duration_seconds INT         NOT NULL CHECK (result_and_share_duration_seconds > 0),
                                entry_fee_gem                     INT         NOT NULL CHECK (entry_fee_gem >= 0),
                                completion_refund_gem             INT         NOT NULL CHECK (completion_refund_gem >= 0),
                                session_status                    VARCHAR(20) NOT NULL,
                                live_status                       VARCHAR(20) NOT NULL,
                                current_round_number              INT         NOT NULL DEFAULT 0,
                                phase_ends_at                     TIMESTAMPTZ,
                                created_at                        TIMESTAMPTZ NOT NULL,
                                updated_at                        TIMESTAMPTZ NOT NULL,
                                CONSTRAINT ck_dating_session_refund_le_fee CHECK (completion_refund_gem <= entry_fee_gem)
);
CREATE INDEX idx_dating_session_status_start ON dating_session (session_status, start_time);

CREATE TABLE session_participant (
                                     id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     session_id         BIGINT       NOT NULL REFERENCES dating_session (id),
                                     member_id          BIGINT       NOT NULL REFERENCES member (id),
                                     gender             VARCHAR(10)  NOT NULL,
                                     seat_no            INT,
                                     alias              VARCHAR(50)  NOT NULL,
                                     participant_status VARCHAR(20)  NOT NULL,
                                     voted_at           TIMESTAMPTZ,
                                     applied_at         TIMESTAMPTZ  NOT NULL,
                                     cancelled_at       TIMESTAMPTZ,
                                     entered_at         TIMESTAMPTZ,
                                     left_at            TIMESTAMPTZ,
                                     CONSTRAINT uk_participant_member UNIQUE (session_id, member_id),
                                     CONSTRAINT uk_participant_seat   UNIQUE (session_id, gender, seat_no),
                                     CONSTRAINT uk_participant_alias  UNIQUE (session_id, alias)
);
CREATE INDEX idx_participant_member ON session_participant (member_id);

CREATE TABLE live_round (
                            id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            session_id   BIGINT      NOT NULL REFERENCES dating_session (id),
                            round_number INT         NOT NULL,
                            round_status VARCHAR(20) NOT NULL,
                            started_at   TIMESTAMPTZ,
                            ended_at     TIMESTAMPTZ,
                            created_at   TIMESTAMPTZ,
                            updated_at   TIMESTAMPTZ,
                            CONSTRAINT uk_live_round_session_round UNIQUE (session_id, round_number)
);

CREATE TABLE live_room (
                           id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           round_id         BIGINT      NOT NULL REFERENCES live_round (id),
                           table_no         INT         NOT NULL,
                           male_member_id   BIGINT      REFERENCES member (id),
                           female_member_id BIGINT      REFERENCES member (id),
                           created_at       TIMESTAMPTZ NOT NULL,
                           updated_at       TIMESTAMPTZ  NOT NULL,
                           CONSTRAINT uk_live_room_round_table UNIQUE (round_id, table_no),
                           CONSTRAINT uk_live_room_round_male  UNIQUE (round_id, male_member_id),
                           CONSTRAINT uk_live_room_round_female    UNIQUE (round_id, female_member_id)
);

-- =========================================================
-- 투표·매칭·연락처
-- =========================================================
CREATE TABLE vote (
                      id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      session_id       BIGINT      NOT NULL REFERENCES dating_session (id),
                      voter_id         BIGINT      NOT NULL REFERENCES member (id),
                      target_member_id BIGINT      NOT NULL REFERENCES member (id),
                      vote_rank        INT         NOT NULL CHECK (vote_rank BETWEEN 1 AND 3),
                      created_at       TIMESTAMPTZ NOT NULL,
                      CONSTRAINT uk_vote_rank   UNIQUE (session_id, voter_id, vote_rank),
                      CONSTRAINT uk_vote_target UNIQUE (session_id, voter_id, target_member_id),
                      CONSTRAINT ck_vote_not_self CHECK (voter_id <> target_member_id)
);

CREATE TABLE match_result (
                              id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              session_id  BIGINT      NOT NULL REFERENCES dating_session (id),
                              member_a_id BIGINT      NOT NULL REFERENCES member (id),
                              member_b_id BIGINT      NOT NULL REFERENCES member (id),
                              created_at  TIMESTAMPTZ NOT NULL,
                              CONSTRAINT uk_match_result UNIQUE (session_id, member_a_id, member_b_id),
    -- (A, B)와 (B, A)가 둘 다 들어가지 않도록 항상 작은 id가 a
                              CONSTRAINT ck_match_order CHECK (member_a_id < member_b_id)
);

CREATE TABLE contact_share (
                               id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               session_id   BIGINT      NOT NULL REFERENCES dating_session (id),
                               sender_id    BIGINT      NOT NULL REFERENCES member (id),
                               receiver_id  BIGINT      NOT NULL REFERENCES member (id),
                               contact_type VARCHAR(20) NOT NULL,
                               share_type   VARCHAR(20) NOT NULL,
                               created_at   TIMESTAMPTZ NOT NULL,
                               CONSTRAINT uk_contact_share UNIQUE (session_id, sender_id, receiver_id),
                               CONSTRAINT ck_contact_share_not_self CHECK (sender_id <> receiver_id)
);
CREATE INDEX idx_contact_share_receiver ON contact_share (receiver_id, created_at DESC);
CREATE INDEX idx_contact_share_sender   ON contact_share (sender_id, created_at DESC);

-- =========================================================
-- 보석·결제
-- =========================================================
CREATE TABLE wallet (
                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        member_id   BIGINT      NOT NULL UNIQUE REFERENCES member (id),
                        gem_balance INT         NOT NULL DEFAULT 0 CHECK (gem_balance >= 0),
                        version     BIGINT      NOT NULL DEFAULT 0,
                        created_at  TIMESTAMPTZ NOT NULL,
                        updated_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE shop_product (
                              id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              name             VARCHAR(100) NOT NULL,
                              gem_amount       INT          NOT NULL CHECK (gem_amount > 0),
                              bonus_gem_amount INT          NOT NULL DEFAULT 0 CHECK (bonus_gem_amount >= 0),
                              price            INT          NOT NULL CHECK (price > 0),
                              active           BOOLEAN      NOT NULL DEFAULT TRUE,
                              created_at       TIMESTAMPTZ  NOT NULL
);

CREATE TABLE payment (
                         id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         member_id      BIGINT       NOT NULL REFERENCES member (id),
                         product_id     BIGINT       NOT NULL REFERENCES shop_product (id),
                         order_id       VARCHAR(100) NOT NULL UNIQUE,
                         payment_key    VARCHAR(255) UNIQUE,
                         amount         INT          NOT NULL CHECK (amount > 0),
                         granted_gem    INT          NOT NULL CHECK (granted_gem > 0),
                         payment_status VARCHAR(20)  NOT NULL,
                         paid_at        TIMESTAMPTZ,
                         canceled_at    TIMESTAMPTZ,
                         cancel_reason  VARCHAR(255),
                         created_at     TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_payment_member ON payment (member_id, created_at DESC);

CREATE TABLE wallet_history (
                                id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                member_id       BIGINT       NOT NULL REFERENCES member (id),
                                type            VARCHAR(30)  NOT NULL,
                                amount          INT          NOT NULL CHECK (amount <> 0),
                                balance_after   INT          NOT NULL CHECK (balance_after >= 0),
                                session_id      BIGINT       REFERENCES dating_session (id),
                                payment_id      BIGINT       REFERENCES payment (id),
                                memo            VARCHAR(255),
                                idempotency_key VARCHAR(100) NOT NULL UNIQUE,
                                created_at      TIMESTAMPTZ  NOT NULL,
                                CONSTRAINT ck_wallet_history_single_ref CHECK (session_id IS NULL OR payment_id IS NULL)
);
CREATE INDEX idx_wallet_history_member ON wallet_history (member_id, created_at DESC);

