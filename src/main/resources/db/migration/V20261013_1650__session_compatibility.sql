CREATE TABLE session_compatibility (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES dating_session (id),
    member_a_id BIGINT NOT NULL REFERENCES member (id),
    member_b_id BIGINT NOT NULL REFERENCES member (id),
    score INT NOT NULL CHECK (score BETWEEN 0 AND 100),
    reason VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_compatibility_member_order CHECK (member_a_id < member_b_id),
    CONSTRAINT uk_session_compatibility_pair UNIQUE (session_id, member_a_id, member_b_id)
);

COMMENT ON TABLE session_compatibility IS '세션 참가자 쌍의 AI 궁합 결과';
